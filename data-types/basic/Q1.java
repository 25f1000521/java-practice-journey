//Declare one variable of each of the 8 primitive data types, assign a suitable value to each, and print all the values.

class DataTypes{
    public static void main(String[] args){
        int year = 2026;
        short age = 42;
        long population = 100000000;
        byte level = 2;
        float percentage = 13.57f;
        double pi = 3.1429472948;
        char grade = 'A';
        boolean isPassed = true;

        System.out.println("int : " + year);
        System.out.println("short : " + age);
        System.out.println("long : " + population);
        System.out.println("byte : " + level);
        System.out.println("float : " + percentage);
        System.out.println("double : " + pi);
        System.out.println("char : " + grade);
        System.out.println("boolean : " + isPassed);
    }
}